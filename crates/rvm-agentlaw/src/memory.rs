//! Cognitive memory bridge using substrate-core's Poincaré distance.

use crate::types::{MemoryPrecedent, RegulatoryDomain};

/// Ball-boundary epsilon. MUST equal the default `eps` of substrate-core's
/// `poincareDistance()` (prediction-bridge.ts) and the kernel's
/// `POINCARE_MAX_NORM = 1 - 1e-5` (substrate-prediction-kernel/src/manifold.rs).
/// Guarded by `tests/poincare_parity.rs`.
pub const POINCARE_EPS: f64 = 1e-5;

/// Embedding dimensionality of the memory engine (classifier query vectors and
/// seed precedents). Synced embeddings of any other dimension are rejected.
pub const MEMORY_DIM: usize = 4;

/// Per-scope quota of synced precedents. Each tenant (and the shared,
/// untenanted scope) has its OWN quota, so one tenant filling its scope can
/// never refuse another tenant's sync. Canonical seeds do not count.
pub const MAX_PRECEDENTS_PER_TENANT: usize = 1_000;

/// Maximum number of distinct sync scopes (tenants + the shared scope).
/// Bounds total memory; a new scope beyond this is refused, existing scopes are
/// unaffected. `auth::ApiKeys` refuses configurations that exceed it.
pub const MAX_TENANT_SCOPES: usize = 64;

/// Absolute upper bound on synced precedents implied by the two limits above.
pub const MAX_PRECEDENTS: usize = MAX_PRECEDENTS_PER_TENANT * MAX_TENANT_SCOPES;

/// Recency half-life used for precedent ranking (30 days).
pub const PRECEDENT_HALF_LIFE_SECONDS: f64 = 86400.0 * 30.0;

/// Reason a synced precedent was refused.
#[derive(Debug, Clone, PartialEq)]
pub enum SyncRejection {
    WrongDimension { expected: usize, got: usize },
    NonFinite { index: usize },
    OutsidePoincareBall { norm: f64 },
    ProtectedPrecedent(String),
    /// The syncing scope has used its whole [`MAX_PRECEDENTS_PER_TENANT`] quota.
    TenantQuotaExceeded { tenant: Option<String>, quota: usize },
    /// A new scope would exceed [`MAX_TENANT_SCOPES`].
    TenantScopesExhausted { max: usize },
    EmptyId,
}

impl std::fmt::Display for SyncRejection {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::WrongDimension { expected, got } => write!(f, "embedding dimension {got} != memory dimension {expected}"),
            Self::NonFinite { index } => write!(f, "embedding component {index} is not finite"),
            Self::OutsidePoincareBall { norm } => write!(f, "embedding norm {norm} is not strictly inside the Poincaré ball (max {})", 1.0 - POINCARE_EPS),
            Self::ProtectedPrecedent(id) => write!(f, "precedent id '{id}' is a canonical seed and cannot be overwritten by sync"),
            Self::TenantQuotaExceeded { tenant, quota } => {
                write!(f, "precedent quota exhausted for tenant '{}' ({quota})", tenant.as_deref().unwrap_or("<shared>"))
            }
            Self::TenantScopesExhausted { max } => write!(f, "precedent store has no free tenant scope (max {max})"),
            Self::EmptyId => write!(f, "precedent_id must be non-empty"),
        }
    }
}

/// Validate a synced embedding at the system boundary (fail-closed).
pub fn validate_embedding(embedding: &[f64]) -> Result<f64, SyncRejection> {
    if embedding.len() != MEMORY_DIM {
        return Err(SyncRejection::WrongDimension { expected: MEMORY_DIM, got: embedding.len() });
    }
    if let Some(index) = embedding.iter().position(|x| !x.is_finite()) {
        return Err(SyncRejection::NonFinite { index });
    }
    let norm = embedding.iter().map(|x| x * x).sum::<f64>().sqrt();
    if norm >= 1.0 - POINCARE_EPS {
        return Err(SyncRejection::OutsidePoincareBall { norm });
    }
    Ok(norm)
}

/// Calculate exact Poincaré conformal distance in hyperbolic space.
/// Same arithmetic (summation order, clamping, `denom <= 0 -> 30`) as
/// `poincareDistance()` in `substrate-core`; parity is verified against a
/// fixture generated by the TS implementation.
///
/// Invalid input (empty, mismatched length, non-finite) returns `f64::MAX`
/// (maximally distant) rather than TS's `0`/`NaN`, so it can never rank as a match.
pub fn poincare_distance(u: &[f64], v: &[f64], eps: f64) -> f64 {
    if u.len() != v.len() || u.is_empty() || u.iter().chain(v.iter()).any(|x| !x.is_finite()) {
        return f64::MAX;
    }

    let mut diff_norm_sq = 0.0;
    let mut u_norm_sq = 0.0;
    let mut v_norm_sq = 0.0;

    for i in 0..u.len() {
        let diff = u[i] - v[i];
        diff_norm_sq += diff * diff;
        u_norm_sq += u[i] * u[i];
        v_norm_sq += v[i] * v[i];
    }

    // Lockstep with Substrate-Core: packages/substrate-core/src/prediction-bridge.ts:76-83
    let max_norm_sq = (1.0 - eps) * (1.0 - eps);
    let clamped_u_sq = u_norm_sq.min(max_norm_sq);
    let clamped_v_sq = v_norm_sq.min(max_norm_sq);

    let denom = (1.0 - clamped_u_sq) * (1.0 - clamped_v_sq);
    if denom <= 0.0 {
        return 30.0;
    }
    let delta = 1.0 + (2.0 * diff_norm_sq) / denom;
    if delta <= 1.0 {
        0.0
    } else {
        (delta + (delta * delta - 1.0).sqrt()).ln()
    }
}

/// Recency weight with a true half-life: `0.5^(age / half_life)`.
///
/// NOTE: this is NOT substrate-core's `applyTemporalDecay()` (which is the T1/T2
/// product `e^(-dt/T1) * e^(-dt/T2)` with T1=3600s, T2=1800s); it is a local
/// ranking heuristic only.
pub fn calculate_temporal_weight(age_seconds: u64, half_life_seconds: f64) -> f64 {
    (-(age_seconds as f64) * std::f64::consts::LN_2 / half_life_seconds).exp()
}

/// In-memory cognitive memory engine simulating substrate-core episodic memory.
pub struct CognitiveMemoryEngine {
    precedents: Vec<StoredPrecedent>,
}

struct StoredPrecedent {
    id: String,
    domain: RegulatoryDomain,
    description: String,
    embedding: Vec<f64>,
    timestamp_utc: u64,
    outcome: String,
    /// Canonical seed precedents cannot be overwritten through the sync API.
    protected: bool,
    /// Owning tenant of a synced precedent. `None` = visible to every tenant
    /// (canonical seeds and precedents synced through the untenanted API).
    tenant: Option<String>,
}

